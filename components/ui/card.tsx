import * as React from "react";
import { cn } from "@/lib/utils";

/**
 * C-Support Card Component
 *
 * Impeccable craft-floor: "States: hover, disabled, loading, error, empty."
 * Card has hover elevation + dark mode support.
 * Shadows carry offset and blur — not decoration.
 */

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-lg border border-border bg-white p-6 shadow-sm",
      // Dark mode support
      "dark:bg-teal-950/50 dark:border-teal-800",
      // Emil hover: only on devices with fine pointer
      "transition-[box-shadow,transform] duration-200 ease-[cubic-bezier(0.23,1,0.32,1)]",
      "hover:shadow-md",
      "dark:hover:shadow-teal-950/30",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

